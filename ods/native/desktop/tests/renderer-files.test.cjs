const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { test } = require('node:test')
const { resolveRendererFile } = require('../renderer-files.cjs')

test('serves built assets and BrowserRouter routes without exposing other files', t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'ods-ui-'))
  t.after(() => fs.rmSync(root, { recursive: true, force: true }))
  fs.writeFileSync(path.join(root, 'index.html'), '<div id="root"></div>')
  fs.mkdirSync(path.join(root, 'assets'))
  fs.writeFileSync(path.join(root, 'assets', 'app.js'), 'console.log("ODS")')
  assert.equal(resolveRendererFile(root, 'ods://app/assets/app.js'), path.join(root, 'assets', 'app.js'))
  assert.equal(resolveRendererFile(root, 'ods://app/models', 'text/html'), path.join(root, 'index.html'))
  assert.equal(resolveRendererFile(root, 'ods://app/missing.js', 'text/html'), null)
  assert.equal(resolveRendererFile(root, 'ods://app/..%2fprivate', 'text/html'), null)
  assert.equal(resolveRendererFile(root, 'ods://app/%00', 'text/html'), null)
  assert.equal(resolveRendererFile(root, 'https://example.com/models', 'text/html'), null)
  assert.equal(resolveRendererFile(root, 'ods://other/models', 'text/html'), null)
  assert.equal(resolveRendererFile(root, 'ods://user:secret@app/models', 'text/html'), null)
})
